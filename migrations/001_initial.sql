PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS schema_version(version INTEGER PRIMARY KEY, applied REAL NOT NULL);
CREATE TABLE IF NOT EXISTS kv(key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS plans(id TEXT PRIMARY KEY, day TEXT NOT NULL, version INTEGER NOT NULL,
 active INTEGER NOT NULL DEFAULT 1, reason TEXT NOT NULL, payload TEXT NOT NULL, created REAL NOT NULL,
 UNIQUE(day,version));
CREATE UNIQUE INDEX IF NOT EXISTS one_active_plan ON plans(day) WHERE active=1;
CREATE TABLE IF NOT EXISTS tasks(id TEXT PRIMARY KEY, plan_id TEXT, day TEXT NOT NULL, type TEXT NOT NULL,
 state TEXT NOT NULL, payload TEXT NOT NULL, earliest REAL NOT NULL, deadline REAL NOT NULL,
 next_run REAL NOT NULL, duration INTEGER NOT NULL, dependencies TEXT NOT NULL DEFAULT '[]',
 attempts INTEGER NOT NULL DEFAULT 0, cancel_requested INTEGER NOT NULL DEFAULT 0,
 owner TEXT, lease_until REAL, result TEXT, error TEXT, created REAL NOT NULL, updated REAL NOT NULL,
 FOREIGN KEY(plan_id) REFERENCES plans(id));
CREATE INDEX IF NOT EXISTS task_queue ON tasks(state,next_run,earliest);
CREATE TABLE IF NOT EXISTS attempts(id INTEGER PRIMARY KEY, task_id TEXT NOT NULL, number INTEGER NOT NULL,
 started REAL NOT NULL, finished REAL, outcome TEXT, error TEXT, UNIQUE(task_id,number));
CREATE TABLE IF NOT EXISTS videos(id TEXT PRIMARY KEY, bvid TEXT NOT NULL, page INTEGER NOT NULL,
 payload TEXT NOT NULL, evidence TEXT NOT NULL, analysis TEXT NOT NULL, state TEXT NOT NULL,
 reason TEXT NOT NULL, created REAL NOT NULL, UNIQUE(bvid,page));
CREATE TABLE IF NOT EXISTS drafts(id TEXT PRIMARY KEY, video_id TEXT NOT NULL, kind TEXT NOT NULL,
 text TEXT NOT NULL, quote TEXT NOT NULL, reason TEXT NOT NULL, status TEXT NOT NULL,
 account TEXT NOT NULL, root TEXT NOT NULL DEFAULT '', parent TEXT NOT NULL DEFAULT '',
 target_uid TEXT NOT NULL DEFAULT '', event_id TEXT UNIQUE, created REAL NOT NULL, updated REAL NOT NULL,
 FOREIGN KEY(video_id) REFERENCES videos(id));
CREATE TABLE IF NOT EXISTS operations(id TEXT PRIMARY KEY, draft_id TEXT NOT NULL UNIQUE,
 state TEXT NOT NULL, account TEXT NOT NULL, day TEXT NOT NULL, video_id TEXT NOT NULL,
 kind TEXT NOT NULL, root TEXT NOT NULL, parent TEXT NOT NULL, target_uid TEXT NOT NULL,
 text TEXT NOT NULL, rpid TEXT UNIQUE, error TEXT, created REAL NOT NULL, updated REAL NOT NULL);
CREATE TABLE IF NOT EXISTS reply_events(id TEXT PRIMARY KEY, payload TEXT NOT NULL, state TEXT NOT NULL, created REAL NOT NULL);
CREATE TABLE IF NOT EXISTS memories(id TEXT PRIMARY KEY, video_id TEXT NOT NULL, text TEXT NOT NULL,
 fingerprint TEXT NOT NULL UNIQUE, importance REAL NOT NULL, topics TEXT NOT NULL,
 source TEXT NOT NULL, status TEXT NOT NULL, context_status TEXT NOT NULL DEFAULT 'not_appended',
 host_status TEXT NOT NULL DEFAULT 'unsupported', created REAL NOT NULL, updated REAL NOT NULL);
CREATE TABLE IF NOT EXISTS memory_sync(id INTEGER PRIMARY KEY, memory_id TEXT NOT NULL, stream_id TEXT NOT NULL,
 method TEXT NOT NULL, status TEXT NOT NULL, created REAL NOT NULL);
CREATE TABLE IF NOT EXISTS interests(topic TEXT PRIMARY KEY, weight REAL NOT NULL, frozen INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS persona_changes(id TEXT PRIMARY KEY, day TEXT NOT NULL, topic TEXT NOT NULL,
 old REAL NOT NULL, new REAL NOT NULL, reason TEXT NOT NULL, sources TEXT NOT NULL, rolled_back INTEGER NOT NULL DEFAULT 0,
 created REAL NOT NULL);
CREATE TABLE IF NOT EXISTS summaries(day TEXT PRIMARY KEY, payload TEXT NOT NULL, text TEXT NOT NULL, created REAL NOT NULL);
CREATE TABLE IF NOT EXISTS budget(day TEXT NOT NULL, resource TEXT NOT NULL, used INTEGER NOT NULL, PRIMARY KEY(day,resource));
CREATE TABLE IF NOT EXISTS model_calls(id TEXT PRIMARY KEY, day TEXT NOT NULL, stage TEXT NOT NULL,
 prompt_version TEXT NOT NULL, model TEXT NOT NULL, state TEXT NOT NULL, usage TEXT NOT NULL,
 created REAL NOT NULL, duration REAL NOT NULL);
CREATE TABLE IF NOT EXISTS audit(id INTEGER PRIMARY KEY, kind TEXT NOT NULL, data TEXT NOT NULL, created REAL NOT NULL);
